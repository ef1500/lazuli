#!/usr/bin/perl
use strict; use warnings;

# Generates test/q3k_vectors.vhdl. Independent reimplementation of
# q3k_unpack.vhdl's documented (best-recall) formula -- if this script
# and the VHDL disagree, that's a real transcription bug in one of
# them, caught by tb_q3k_unpack.vhdl comparing DUT output against these
# constants. Perl, not Python (test/gen/'s other generators are Python),
# because no Python interpreter was available in the environment this
# was written in -- functionally the same kind of generator, just a
# different scripting language.
#
# Regenerate with: perl test/gen/gen_q3k_vectors.pl > test/q3k_vectors.vhdl

srand(12345);

sub rand_block {
    my @b;
    push @b, int(rand(256)) for (1..110);
    return @b;
}

sub unpack_q3k {
    my (@b) = @_;
    my @hmask = @b[0..31];
    my @qs    = @b[32..95];
    my @sc    = @b[96..107];

    my (@aux0, @aux1, @tmp);
    for my $i (0..3) {
        $aux0[$i] = $sc[$i];
        $aux1[$i] = $sc[4+$i];
        $tmp[$i]  = $sc[8+$i];
    }
    my @scale_bytes = (0) x 16;
    for my $i (0..3) {
        $scale_bytes[0*4+$i] = ($aux0[$i] & 0x0F) | (($tmp[$i] & 0x03) << 4);
        $scale_bytes[1*4+$i] = ($aux1[$i] & 0x0F) | ((($tmp[$i]>>2) & 0x03) << 4);
        $scale_bytes[2*4+$i] = (($aux0[$i]>>4) & 0x0F) | ((($tmp[$i]>>4) & 0x03) << 4);
        $scale_bytes[3*4+$i] = (($aux1[$i]>>4) & 0x0F) | ((($tmp[$i]>>6) & 0x03) << 4);
    }

    my @weight;
    my @scale;
    for my $g (0..15) {
        my $half = int($g/8);
        my $j = int(($g % 8)/2);
        my $sub = $g % 2;
        my $shift = $j*2;
        my $m_bit = $half*4+$j;
        my $qs_base = $half*32+$sub*16;
        my $hm_base = $sub*16;
        $scale[$g] = $scale_bytes[$g] & 0x3F;
        for my $r (0..15) {
            my $q2bit = ($qs[$qs_base+$r] >> $shift) & 0x3;
            my $hbit = ($hmask[$hm_base+$r] >> $m_bit) & 0x1;
            my $raw3 = $q2bit | ($hbit << 2);
            $weight[$g][$r] = $raw3 - 4;
        }
    }
    return (\@weight, \@scale);
}

my $nvec = 6;
my (@blocks_hex, @weights_flat, @scales_flat, @d_vals);

for my $v (0..$nvec-1) {
    my @b = $v == 0 ? ((0) x 110)
          : $v == 1 ? ((0xFF) x 110)
          : rand_block();
    my ($w, $s) = unpack_q3k(@b);

    my $hex = join('', map { sprintf("%02X", $_) } reverse @b);
    push @blocks_hex, $hex;
    push @d_vals, sprintf("16#%02X%02X#", $b[109], $b[108]);

    my @wflat;
    for my $g (0..15) { for my $r (0..15) { push @wflat, $w->[$g][$r]; } }
    push @weights_flat, join(",", @wflat);
    push @scales_flat, join(",", @$s);
}

print "-- AUTO-GENERATED by test/gen/gen_q3k_vectors.pl -- do not hand-edit.\n";
print "-- Regenerate with: perl test/gen/gen_q3k_vectors.pl > test/q3k_vectors.vhdl\n";
print "library IEEE;\n";
print "use IEEE.STD_LOGIC_1164.ALL;\n\n";
print "package q3k_vectors is\n";
print "  constant NUM_VEC : positive := $nvec;\n\n";
print "  type block_arr_t is array (0 to NUM_VEC - 1) of std_logic_vector(879 downto 0);\n";
print "  constant blocks : block_arr_t := (\n";
print join(",\n", map { "    $_ => x\"$blocks_hex[$_]\"" } (0..$nvec-1)), "\n";
print "  );\n\n";

print "  type weight_arr_t is array (0 to NUM_VEC - 1, 0 to 255) of integer;\n";
print "  constant expected_weights : weight_arr_t := (\n";
for my $v (0..$nvec-1) {
    print "    $v => ($weights_flat[$v])" . ($v < $nvec-1 ? ",\n" : "\n");
}
print "  );\n\n";

print "  type scale_arr_t is array (0 to NUM_VEC - 1, 0 to 15) of integer;\n";
print "  constant expected_scales : scale_arr_t := (\n";
for my $v (0..$nvec-1) {
    print "    $v => ($scales_flat[$v])" . ($v < $nvec-1 ? ",\n" : "\n");
}
print "  );\n\n";

print "  type d_arr_t is array (0 to NUM_VEC - 1) of integer;\n";
print "  constant expected_d : d_arr_t := (", join(",", @d_vals), ");\n";
print "end package q3k_vectors;\n";
