#!/usr/bin/perl
use strict; use warnings;

# Generates test/q4k_vectors.vhdl -- see gen_q3k_vectors.pl's header for
# the rationale (independent reimplementation, not copy-pasted from the
# VHDL, Perl instead of Python for environment reasons).
#
# Regenerate with: perl test/gen/gen_q4k_vectors.pl > test/q4k_vectors.vhdl

srand(99999);

sub rand_block {
    my @b;
    push @b, int(rand(256)) for (1..144);
    return @b;
}

sub get_scale_min_k4 {
    my ($j, @q) = @_; # q = scales[0..11]
    my ($sc, $m);
    if ($j < 4) {
        $sc = $q[$j] & 0x3F;
        $m  = $q[$j+4] & 0x3F;
    } else {
        $sc = ($q[$j+4] & 0x0F) | ((($q[$j-4] >> 6) & 0x3) << 4);
        $m  = ($q[$j+4] >> 4)   | ((($q[$j]    >> 6) & 0x3) << 4);
    }
    return ($sc, $m);
}

sub unpack_q4k {
    my (@b) = @_;
    my @scales = @b[4..15];
    my @qs     = @b[16..143];

    my @weight;
    my @scale;
    my @min;
    for my $c (0..15) {
        my $group_idx = int($c/2);
        my $j_outer = int($group_idx/2);
        my $nibble_bit = $group_idx % 2;
        my $subhalf = $c % 2;
        my $qs_base = $j_outer*32 + $subhalf*16;

        my ($sc, $m) = get_scale_min_k4($group_idx, @scales);
        $scale[$c] = $sc;
        $min[$c] = $m;

        for my $r (0..15) {
            my $byte = $qs[$qs_base + $r];
            my $nibble = $nibble_bit == 1 ? (($byte >> 4) & 0xF) : ($byte & 0xF);
            $weight[$c][$r] = $nibble - 8;
        }
    }
    return (\@weight, \@scale, \@min);
}

my $nvec = 6;
my (@blocks_hex, @weights_flat, @scales_flat, @mins_flat, @d_vals, @dmin_vals);

for my $v (0..$nvec-1) {
    my @b = $v == 0 ? ((0) x 144)
          : $v == 1 ? ((0xFF) x 144)
          : rand_block();
    my ($w, $s, $m) = unpack_q4k(@b);

    my $hex = join('', map { sprintf("%02X", $_) } reverse @b);
    push @blocks_hex, $hex;
    push @d_vals, sprintf("16#%02X%02X#", $b[1], $b[0]);
    push @dmin_vals, sprintf("16#%02X%02X#", $b[3], $b[2]);

    my @wflat;
    for my $c (0..15) { for my $r (0..15) { push @wflat, $w->[$c][$r]; } }
    push @weights_flat, join(",", @wflat);
    push @scales_flat, join(",", @$s);
    push @mins_flat, join(",", @$m);
}

print "-- AUTO-GENERATED by test/gen/gen_q4k_vectors.pl -- do not hand-edit.\n";
print "-- Regenerate with: perl test/gen/gen_q4k_vectors.pl > test/q4k_vectors.vhdl\n";
print "library IEEE;\n";
print "use IEEE.STD_LOGIC_1164.ALL;\n\n";
print "package q4k_vectors is\n";
print "  constant NUM_VEC : positive := $nvec;\n\n";
print "  type block_arr_t is array (0 to NUM_VEC - 1) of std_logic_vector(1151 downto 0);\n";
print "  constant blocks : block_arr_t := (\n";
print join(",\n", map { "    $_ => x\"$blocks_hex[$_]\"" } (0..$nvec-1)), "\n";
print "  );\n\n";

print "  type weight_arr_t is array (0 to NUM_VEC - 1, 0 to 255) of integer;\n";
print "  constant expected_weights : weight_arr_t := (\n";
for my $v (0..$nvec-1) {
    print "    $v => ($weights_flat[$v])" . ($v < $nvec-1 ? ",\n" : "\n");
}
print "  );\n\n";

print "  type scale_arr_t is array (0 to NUM_VEC - 1, 0 to 15) of integer;\n";
print "  constant expected_scales : scale_arr_t := (\n";
for my $v (0..$nvec-1) {
    print "    $v => ($scales_flat[$v])" . ($v < $nvec-1 ? ",\n" : "\n");
}
print "  );\n\n";

print "  constant expected_mins : scale_arr_t := (\n";
for my $v (0..$nvec-1) {
    print "    $v => ($mins_flat[$v])" . ($v < $nvec-1 ? ",\n" : "\n");
}
print "  );\n\n";

print "  type d_arr_t is array (0 to NUM_VEC - 1) of integer;\n";
print "  constant expected_d : d_arr_t := (", join(",", @d_vals), ");\n";
print "  constant expected_dmin : d_arr_t := (", join(",", @dmin_vals), ");\n";
print "end package q4k_vectors;\n";
