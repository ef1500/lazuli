#!/usr/bin/perl
use strict; use warnings;

# Generates test/q6k_vectors.vhdl -- see gen_q3k_vectors.pl's header for
# the rationale (independent reimplementation, not copy-pasted from the
# VHDL, Perl instead of Python for environment reasons).
#
# Regenerate with: perl test/gen/gen_q6k_vectors.pl > test/q6k_vectors.vhdl

srand(54321);

sub rand_block {
    my @b;
    push @b, int(rand(256)) for (1..210);
    return @b;
}

sub signed8 {
    my $v = shift;
    return $v >= 128 ? $v - 256 : $v;
}

sub unpack_q6k {
    my (@b) = @_;
    my @ql = @b[0..127];
    my @qh = @b[128..191];
    my @sc = @b[192..207];

    my @weight;
    my @scale;
    for my $g (0..15) {
        my $n_half   = int($g/8);
        my $subgroup = int(($g % 8)/2);
        my $is_bit    = $g % 2;

        my $shift   = $subgroup * 2;
        my $ql_base = $n_half*64 + ($subgroup % 2)*32 + $is_bit*16;
        my $qh_base = $n_half*32 + $is_bit*16;
        my $use_hi  = $subgroup >= 2;

        $scale[$g] = signed8($sc[$g]);

        for my $r (0..15) {
            my $ql_byte = $ql[$ql_base + $r];
            my $qh_byte = $qh[$qh_base + $r];
            my $nibble = $use_hi ? (($ql_byte >> 4) & 0xF) : ($ql_byte & 0xF);
            my $hi2 = ($qh_byte >> $shift) & 0x3;
            my $raw6 = $nibble | ($hi2 << 4);
            $weight[$g][$r] = $raw6 - 32;
        }
    }
    return (\@weight, \@scale);
}

my $nvec = 6;
my (@blocks_hex, @weights_flat, @scales_flat, @d_vals);

for my $v (0..$nvec-1) {
    my @b = $v == 0 ? ((0) x 210)
          : $v == 1 ? ((0xFF) x 210)
          : rand_block();
    my ($w, $s) = unpack_q6k(@b);

    my $hex = join('', map { sprintf("%02X", $_) } reverse @b);
    push @blocks_hex, $hex;
    push @d_vals, sprintf("16#%02X%02X#", $b[209], $b[208]);

    my @wflat;
    for my $g (0..15) { for my $r (0..15) { push @wflat, $w->[$g][$r]; } }
    push @weights_flat, join(",", @wflat);
    push @scales_flat, join(",", @$s);
}

print "-- AUTO-GENERATED by test/gen/gen_q6k_vectors.pl -- do not hand-edit.\n";
print "-- Regenerate with: perl test/gen/gen_q6k_vectors.pl > test/q6k_vectors.vhdl\n";
print "library IEEE;\n";
print "use IEEE.STD_LOGIC_1164.ALL;\n\n";
print "package q6k_vectors is\n";
print "  constant NUM_VEC : positive := $nvec;\n\n";
print "  type block_arr_t is array (0 to NUM_VEC - 1) of std_logic_vector(1679 downto 0);\n";
print "  constant blocks : block_arr_t := (\n";
print join(",\n", map { "    $_ => x\"$blocks_hex[$_]\"" } (0..$nvec-1)), "\n";
print "  );\n\n";

print "  type weight_arr_t is array (0 to NUM_VEC - 1, 0 to 255) of integer;\n";
print "  constant expected_weights : weight_arr_t := (\n";
for my $v (0..$nvec-1) {
    print "    $v => ($weights_flat[$v])" . ($v < $nvec-1 ? ",\n" : "\n");
}
print "  );\n\n";

print "  type scale_arr_t is array (0 to NUM_VEC - 1, 0 to 15) of integer;\n";
print "  constant expected_scales : scale_arr_t := (\n";
for my $v (0..$nvec-1) {
    print "    $v => ($scales_flat[$v])" . ($v < $nvec-1 ? ",\n" : "\n");
}
print "  );\n\n";

print "  type d_arr_t is array (0 to NUM_VEC - 1) of integer;\n";
print "  constant expected_d : d_arr_t := (", join(",", @d_vals), ");\n";
print "end package q6k_vectors;\n";
