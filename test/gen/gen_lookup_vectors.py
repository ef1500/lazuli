"""Regenerates test/lookup_vectors.vhdl: golden LUT+slope tables and
evaluation cases for generic_lookup.vhdl (recip, rsqrt, exp2, sigmoid,
silu, gelu), checked against Python's math/numpy, not the VHDL's own
derivation of the addressing scheme.

    python test/gen/gen_lookup_vectors.py
"""
import struct, random, math, sys, os
import numpy as np

def f32_bits(x):
    x = float(x)
    try:
        return struct.unpack('<I', struct.pack('<f', x))[0]
    except OverflowError:
        return 0x7F7FFFFF if x > 0 else 0xFF7FFFFF

def bits_f32(u):
    return struct.unpack('<f', struct.pack('<I', u & 0xFFFFFFFF))[0]

random.seed(7)

def erf_gelu(x):
    return 0.5 * x * (1.0 + math.erf(x / math.sqrt(2.0)))

def sigmoid(x):
    return 1.0 / (1.0 + math.exp(-x))

def silu(x):
    return x * sigmoid(x)

def build_mant_table(fn, idxbits):
    n = 2 ** idxbits
    entries = []
    for i in range(n):
        m_lo = 1.0 + i / n
        m_hi = 1.0 + (i + 1) / n
        v0 = fn(m_lo)
        v1 = fn(m_hi)
        entries.append((f32_bits(v0), f32_bits(v1 - v0)))
    return entries

def build_rsqrt_table(idxbits):
    n = 2 ** idxbits
    entries = []
    half = n // 2
    for idx in range(n):
        p = idx // half
        mi = idx % half
        m_lo = 1.0 + mi / half
        m_hi = 1.0 + (mi + 1) / half
        dom_lo = m_lo * (2 ** p)
        dom_hi = m_hi * (2 ** p)
        v0 = 1.0 / math.sqrt(dom_lo)
        v1 = 1.0 / math.sqrt(dom_hi)
        entries.append((f32_bits(v0), f32_bits(v1 - v0)))
    return entries

def build_frac_table(fn, idxbits):
    n = 2 ** idxbits
    entries = []
    for i in range(n):
        f_lo = i / n
        f_hi = (i + 1) / n
        v0 = fn(f_lo)
        v1 = fn(f_hi)
        entries.append((f32_bits(v0), f32_bits(v1 - v0)))
    return entries

def build_range_table(fn, lo, hi, idxbits):
    n = 2 ** idxbits
    step = (hi - lo) / n
    entries = []
    for i in range(n):
        x0 = lo + i * step
        x1 = lo + (i + 1) * step
        v0 = fn(x0)
        v1 = fn(x1)
        entries.append((f32_bits(v0), f32_bits(v1 - v0)))
    return entries

SLOTS = {}
SLOTS[0] = dict(mode='TAB_MANT', bits=7, lo=0.0, hi=0.0, left='EDGE_CLAMP', right='EDGE_CLAMP',
                 table=build_mant_table(lambda m: 1.0 / m, 7))
SLOTS[1] = dict(mode='TAB_RSQRT', bits=8, lo=0.0, hi=0.0, left='EDGE_CLAMP', right='EDGE_CLAMP',
                 table=build_rsqrt_table(8))
SLOTS[2] = dict(mode='TAB_FRAC', bits=7, lo=0.0, hi=0.0, left='EDGE_CLAMP', right='EDGE_CLAMP',
                 table=build_frac_table(lambda f: 2.0 ** f, 7))
SLOTS[3] = dict(mode='TAB_RANGE', bits=10, lo=-16.0, hi=16.0, left='EDGE_CLAMP', right='EDGE_CLAMP',
                 table=build_range_table(sigmoid, -16.0, 16.0, 10))
SLOTS[4] = dict(mode='TAB_RANGE', bits=10, lo=-16.0, hi=16.0, left='EDGE_ZERO', right='EDGE_IDENTITY',
                 table=build_range_table(silu, -16.0, 16.0, 10))
SLOTS[5] = dict(mode='TAB_RANGE', bits=10, lo=-8.0, hi=8.0, left='EDGE_ZERO', right='EDGE_IDENTITY',
                 table=build_range_table(erf_gelu, -8.0, 8.0, 10))

cases = []  # (slot, x_bits, expect_real, tol_abs, tol_rel, name)

for _ in range(300):
    e = random.uniform(-30, 30)
    m = random.uniform(1.0, 2.0)
    x = m * (2 ** e)
    if random.random() < 0.5:
        x = -x
    expect = 1.0 / x
    cases.append((0, f32_bits(x), expect, 0, 3e-4, f"recip {x}"))

for _ in range(300):
    e = random.uniform(-30, 30)
    m = random.uniform(1.0, 2.0)
    x = m * (2 ** e)
    expect = 1.0 / math.sqrt(x)
    cases.append((1, f32_bits(x), expect, 0, 3e-4, f"rsqrt {x}"))

for _ in range(300):
    x = random.uniform(-200.0, 200.0)
    expect = 2.0 ** x
    cases.append((2, f32_bits(x), expect, 0, 2e-3, f"exp2 {x}"))
for iv in [-5, -1, 0, 1, 5, 10, -10]:
    expect = 2.0 ** iv
    cases.append((2, f32_bits(float(iv)), expect, 0, 2e-3, f"exp2 int {iv}"))

for _ in range(200):
    x = random.uniform(-30.0, 30.0)
    expect = sigmoid(x)
    cases.append((3, f32_bits(x), expect, 2e-3, 0, f"sigmoid {x}"))
for _ in range(200):
    x = random.uniform(-30.0, 30.0)
    expect = silu(x)
    cases.append((4, f32_bits(x), expect, 5e-3, 1e-3, f"silu {x}"))
for _ in range(200):
    x = random.uniform(-15.0, 15.0)
    expect = erf_gelu(x)
    cases.append((5, f32_bits(x), expect, 5e-3, 1e-3, f"gelu {x}"))

print(len(cases), "eval cases", file=sys.stderr)

out_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'lookup_vectors.vhdl')
with open(out_path, 'w') as f:
    f.write("-- AUTO-GENERATED by test/gen/gen_lookup_vectors.py -- do not hand-edit.\n")
    f.write("-- Regenerate with: python test/gen/gen_lookup_vectors.py\n")
    f.write("library IEEE;\nuse IEEE.STD_LOGIC_1164.ALL;\nuse IEEE.NUMERIC_STD.ALL;\nuse work.project_types.all;\n\n")
    f.write("package lookup_vectors is\n")

    f.write("  type entry_t is record\n    value : std_logic_vector(31 downto 0);\n    slope : std_logic_vector(31 downto 0);\n  end record;\n")
    for s in SLOTS:
        n = len(SLOTS[s]['table'])
        f.write(f"  type entry_arr_{s}_t is array (0 to {n-1}) of entry_t;\n")
        f.write(f"  constant TABLE_{s} : entry_arr_{s}_t := (\n")
        for i,(v,sl) in enumerate(SLOTS[s]['table']):
            comma = ',' if i < n-1 else ''
            f.write(f'    (x"{v:08X}", x"{sl:08X}"){comma}\n')
        f.write("  );\n")

    f.write("  type slot_load_t is record\n")
    f.write("    mode : tab_mode_t;\n    lo, hi : std_logic_vector(31 downto 0);\n")
    f.write("    left, right : tab_edge_t;\n    bits : natural;\n  end record;\n")
    f.write(f"  type slot_load_arr_t is array (0 to {len(SLOTS)-1}) of slot_load_t;\n")
    f.write("  constant SLOT_CFG : slot_load_arr_t := (\n")
    for i,s in enumerate(SLOTS):
        c = SLOTS[s]
        comma = ',' if i < len(SLOTS)-1 else ''
        f.write(f'    ({c["mode"]}, x"{f32_bits(c["lo"]):08X}", x"{f32_bits(c["hi"]):08X}", {c["left"]}, {c["right"]}, {c["bits"]}){comma}\n')
    f.write("  );\n")

    f.write("  type case_t is record\n")
    f.write("    slot : natural;\n    x : std_logic_vector(31 downto 0);\n")
    f.write("    expect : std_logic_vector(31 downto 0);\n")
    f.write("    tol_abs : std_logic_vector(31 downto 0);\n")
    f.write("    tol_rel_ppm : natural;\n")
    f.write("  end record;\n")
    f.write(f"  type case_arr_t is array (0 to {len(cases)-1}) of case_t;\n")
    f.write("  constant CASES : case_arr_t := (\n")
    for i,(slot,xb,expect,tol_abs,tol_rel,name) in enumerate(cases):
        eb = f32_bits(expect)
        tb = f32_bits(tol_abs) if tol_abs else f32_bits(0.0)
        ppm = int(tol_rel*1e6)
        comma = ',' if i < len(cases)-1 else ''
        f.write(f'    ({slot}, x"{xb:08X}", x"{eb:08X}", x"{tb:08X}", {ppm}){comma} -- {name}\n')
    f.write("  );\nend package lookup_vectors;\n")

print("wrote", out_path, ":", len(cases), "cases,", sum(len(SLOTS[s]['table']) for s in SLOTS), "table entries total")
